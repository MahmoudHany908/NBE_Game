using UnityEngine;
using UnityEngine.UI;

namespace VaultSurvivors.UI
{
    [RequireComponent(typeof(RectTransform))]
    public class CooldownDemonstrator : MonoBehaviour
    {
        [Header("Cooldown Settings")]
        [Tooltip("How many seconds the cooldown takes to complete.")]
        public float cooldownDuration = 3f;

        [Tooltip("The color of the cooldown overlay.")]
        public Color overlayColor = new Color(0f, 0f, 0f, 0.7f);

        private Image _overlayImage;
        private float _timer;

        private void Start()
        {
            // 1. Create a new child GameObject for the overlay so we don't mess up the original image
            GameObject overlayGo = new GameObject("CooldownOverlay_AutoGenerated");
            overlayGo.transform.SetParent(this.transform, false);

            // 2. Set it up to perfectly stretch and match the parent's exact dimensions
            RectTransform rect = overlayGo.AddComponent<RectTransform>();
            rect.anchorMin = Vector2.zero; // Bottom Left
            rect.anchorMax = Vector2.one;  // Top Right
            rect.offsetMin = Vector2.zero; // 0 margin
            rect.offsetMax = Vector2.zero; // 0 margin
            
            // 3. Add the Image component and configure it as a standard Radial timer
            _overlayImage = overlayGo.AddComponent<Image>();
            _overlayImage.color = overlayColor;
            
            // Unity's "Filled" Image type REQUIRES a sprite to be assigned!
            // If the sprite is null, the fillAmount property is completely ignored.
            // We will copy the parent's sprite so it perfectly matches the shape of the icon.
            var parentImage = GetComponent<Image>();
            if (parentImage != null)
            {
                _overlayImage.sprite = parentImage.sprite;
            }
            
            // Set type to Filled for the classic clock wipe effect
            _overlayImage.type = Image.Type.Filled;
            _overlayImage.fillMethod = Image.FillMethod.Radial360;
            _overlayImage.fillOrigin = (int)Image.Origin360.Top;
            _overlayImage.fillClockwise = false; // Standard MOBA style draining

            // Ensure Raycast target is off so it doesn't accidentally block mouse clicks on your actual buttons
            _overlayImage.raycastTarget = false;

            _timer = cooldownDuration;
        }

        private void Update()
        {
            if (_overlayImage == null) return;

            _timer -= Time.deltaTime;

            if (_timer <= 0f)
            {
                // Restart the cooldown indefinitely for demonstration purposes
                _timer = cooldownDuration;
            }

            // Fill Amount: 1 is fully dark (just used ability), 0 is completely clear (ready to use)
            _overlayImage.fillAmount = _timer / cooldownDuration;
        }
    }
}
